#!/usr/bin/env python3
"""SSB-X.sln, SSB-X.vcxproj and SSB-X.vcxproj.filters: a native RXDK project.

The project is RXDK's own `Rxdk.Cli generate-vcxproj` output for
rxdk.project.json -- the same shape as the SDK samples: the RXDK platform
toolset, every source named, property pages for the include paths,
defines, flags, libraries and image settings, the data folder packed into
the ISO, and F5 the Xbox Debugger (RXDK). On top of it, this adds what a
sample does not need and this port does:

  * a Pre-Build Event that runs build.bat --skip-build: the decomp, the
    assets exported from your ROM, the generated sources the project
    compiles (Platform\\xbox\\gen) and data\\. A fresh clone with
    baserom.z64 in it therefore builds straight from Visual Studio;
  * the project GUID fixed, so regenerating it changes nothing;
  * the headers and a folder tree, for browsing.

The source list comes from the Makefile (through gen_manifest.py), so the
committed project goes stale only when a source is added or removed;
setup.py notices and says to run this. RXDK's native build names each
object after its file alone, so two sources with one name would overwrite
each other's object: this refuses to generate such a project.

    python tools/xbox/gen_vcxproj.py            # regenerate (after gen_manifest)
    python tools/xbox/gen_vcxproj.py --check    # exit 1 when the project is stale
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import prereqs  # noqa: E402

NAME = "SSB-X"
PROJ = os.path.join(ROOT, NAME + ".vcxproj")
SLN = os.path.join(ROOT, NAME + ".sln")
FILTERS = PROJ + ".filters"
MANIFEST = os.path.join(ROOT, "rxdk.project.json")
GUID = "{52A4D51C-B137-52FF-B64D-25D13693AA17}"
HEADER_TREES = [("Platform/xbox", ["gen"]), ("src/dc", [])]

HEADER_COMMENT = """<!--
  SSB-X: a native RXDK project, generated by tools/xbox/gen_vcxproj.py from rxdk.project.json
  (Rxdk.Cli generate-vcxproj, plus a Pre-Build Event). Build like any RXDK sample; F5 is the
  Xbox Debugger (RXDK).

  The Pre-Build Event runs build.bat with skip-build: it checks the prerequisites, fetches the
  decomp, exports what is out of date from baserom.z64, and writes the generated sources this
  project compiles (Platform\\xbox\\gen) and data\\. Then RXDK compiles, links and packs the ISO.

  Do not edit the file list by hand: after adding or removing a source, run
  python tools/xbox/gen_vcxproj.py (setup.py says when it is due).
-->
"""

PREBUILD = """  <ItemDefinitionGroup>
    <PreBuildEvent>
      <Command>set SSBX_NONINTERACTIVE=1
call "$(ProjectDir)build.bat" --skip-build --config $(Configuration)</Command>
      <Message>SSB-X: prerequisites, assets from baserom.z64, generated sources and data (build.bat --skip-build)</Message>
    </PreBuildEvent>
  </ItemDefinitionGroup>
"""

NONE_ITEMS = ["build.bat", "setup.py", "rxdk.project.json", "README.md",
              "Platform\\xbox\\titleimage.rdf", "Platform\\xbox\\saveimage.rdf"]


def manifest_sources(cfg="Release"):
    m = json.load(open(MANIFEST, encoding="utf-8"))
    return [s.replace("/", "\\") for s in m["configurations"][cfg]["sources"]]


def project_sources(text):
    return re.findall(r'<ClCompile Include="([^"]+)"', text)


def headers():
    out = []
    for top, skip in HEADER_TREES:
        base = os.path.join(ROOT, top)
        for d, subs, fs in os.walk(base):
            subs[:] = sorted(s for s in subs if s not in skip and not s.startswith("."))
            out += [os.path.relpath(os.path.join(d, f), ROOT).replace("/", "\\")
                    for f in sorted(fs) if f.endswith(".h")]
    return out


def crlf(text):
    return text.replace("\r\n", "\n").replace("\n", "\r\n")


def write_if_changed(path, text):
    data = text.encode("utf-8")
    if os.path.isfile(path) and open(path, "rb").read() == data:
        return False
    with open(path, "wb") as f:
        f.write(data)
    return True


def rxdk_generate():
    """RXDK's own project for the manifest, as (vcxproj, sln) text."""
    cli = prereqs.find_rxdk_cli()
    if not cli:
        raise SystemExit("gen_vcxproj: Rxdk.Cli not found (python setup.py installs RXDK)")
    with tempfile.TemporaryDirectory() as tmp:
        shutil.copy2(MANIFEST, os.path.join(tmp, "rxdk.project.json"))
        r = subprocess.run([cli, "generate-vcxproj", "--project-root", tmp],
                           capture_output=True, text=True)
        p, s = os.path.join(tmp, NAME + ".vcxproj"), os.path.join(tmp, NAME + ".sln")
        if r.returncode != 0 or not os.path.isfile(p):
            raise SystemExit("gen_vcxproj: Rxdk.Cli generate-vcxproj failed:\n" + r.stdout + r.stderr)
        return (open(p, encoding="utf-8-sig").read(), open(s, encoding="utf-8-sig").read())


def build_filters(files):
    folders = set()
    for _kind, f in files:
        d = os.path.dirname(f)
        while d:
            folders.add(d)
            d = os.path.dirname(d)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">',
             "  <ItemGroup>"]
    for d in sorted(folders):
        lines += ['    <Filter Include="%s">' % d,
                  "      <UniqueIdentifier>{%s}</UniqueIdentifier>"
                  % uuid.uuid5(uuid.NAMESPACE_URL, "ssb-x/" + d),
                  "    </Filter>"]
    lines += ["  </ItemGroup>", "  <ItemGroup>"]
    for kind, f in files:
        d = os.path.dirname(f)
        if d:
            lines += ['    <%s Include="%s">' % (kind, f), "      <Filter>%s</Filter>" % d,
                      "    </%s>" % kind]
        else:
            lines.append('    <%s Include="%s" />' % (kind, f))
    lines += ["  </ItemGroup>", "</Project>", ""]
    return "\n".join(lines)


def generate():
    srcs = manifest_sources()
    seen = {}
    for s in srcs:
        b = os.path.basename(s.replace("\\", "/")).lower()
        if b in seen:
            raise SystemExit("gen_vcxproj: %s and %s share a file name; RXDK's native build "
                             "would overwrite one object with the other -- rename one"
                             % (seen[b], s))
        seen[b] = s
    proj, sln = rxdk_generate()
    proj, sln = proj.replace("\r\n", "\n"), sln.replace("\r\n", "\n")
    old = re.search(r"<ProjectGuid>(\{[0-9A-Fa-f-]+\})</ProjectGuid>", proj).group(1)
    proj = proj.replace(old, GUID)
    sln = re.sub(re.escape(old), GUID, sln, flags=re.I)
    proj = proj.replace("<RootNamespace>XboxNamespace</RootNamespace>",
                        "<RootNamespace>SSB_X</RootNamespace>")
    proj = proj.replace('<?xml version="1.0" encoding="utf-8"?>\n',
                        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER_COMMENT, 1)
    hdrs = headers()
    extra = PREBUILD
    extra += "  <ItemGroup>\n" + "".join('    <ClInclude Include="%s" />\n' % h for h in hdrs) \
        + "  </ItemGroup>\n"
    extra += "  <ItemGroup>\n" + "".join('    <None Include="%s" />\n' % n for n in NONE_ITEMS) \
        + "  </ItemGroup>\n"
    tail = '  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.targets" />'
    if tail not in proj:
        raise SystemExit("gen_vcxproj: RXDK's project has no Microsoft.Cpp.targets import")
    proj = proj.replace(tail, extra + tail, 1)
    if project_sources(proj) != srcs:
        raise SystemExit("gen_vcxproj: RXDK's project does not list the manifest's sources")
    files = ([("ClCompile", s) for s in srcs] + [("ClInclude", h) for h in hdrs]
             + [("None", n) for n in NONE_ITEMS])
    changed = [os.path.basename(p) for p, t in
               ((PROJ, crlf(proj)), (SLN, crlf(sln)), (FILTERS, crlf(build_filters(files))))
               if write_if_changed(p, t)]
    print("gen_vcxproj: %d sources, %d headers -> %s" % (
        len(srcs), len(hdrs), ", ".join(changed) if changed else "unchanged"))


def in_sync():
    """Whether the committed project lists exactly the manifest's sources."""
    if not os.path.isfile(PROJ):
        return False
    return project_sources(open(PROJ, encoding="utf-8-sig").read()) == manifest_sources()


def main():
    if "--check" in sys.argv[1:]:
        ok = in_sync()
        print("gen_vcxproj: %s" % ("in step with rxdk.project.json" if ok else
                                   "STALE -- run python tools/xbox/gen_vcxproj.py"))
        sys.exit(0 if ok else 1)
    generate()


if __name__ == "__main__":
    main()
