#!/usr/bin/env python3
"""Turn the Makefile's absolute-symbol linker scripts into a C file.

The Dreamcast link passes two generated GNU ld scripts,
src/game/ssb64/particlebanks.ld and wpattrs.ld, each a list of

    _lEFCommonParticleScriptBankLo = 0x00ac7340;

-- absolute symbols, so `&lEFCommonParticleScriptBankLo` is that number with
no storage behind it (src/dc/dma.c turns the ROM address back into a file;
src/dc/wpattrs.c reads an offset). lld's COFF mode takes no ld script, but
a COFF object can define absolute symbols, so the same lines become
`.set` directives in Platform/xbox/gen/abs_symbols.c. The names already
carry the leading underscore 32-bit COFF gives a C symbol (the exporters
run with --symbol-prefix _), exactly as on the SH-4.

Always regenerated: the scripts are derived from the ROM by the exporters.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GAME = os.path.join(ROOT, "src", "game", "ssb64")
OUT = os.path.join(ROOT, "Platform", "xbox", "gen", "abs_symbols.c")
SCRIPTS = ["particlebanks.ld", "wpattrs.ld"]

LINE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*;")


def main():
    rows = []
    for name in SCRIPTS:
        path = os.path.join(GAME, name)
        if not os.path.exists(path):
            raise SystemExit("gen_absyms: %s missing -- run the asset step first "
                             "(python setup.py)" % os.path.relpath(path, ROOT))
        n = 0
        for line in open(path, encoding="utf-8"):
            m = LINE.match(line)
            if m:
                rows.append((name, m.group(1), int(m.group(2), 0)))
                n += 1
        if n == 0:
            raise SystemExit("gen_absyms: no symbols in %s" % name)
    out = ["/* GENERATED by tools/xbox/gen_absyms.py from src/game/ssb64/%s -- do not edit."
           % " and ".join(SCRIPTS),
           " *",
           " * Absolute symbols: the address IS the value (see the generator). */",
           ""]
    for src, sym, val in rows:
        out.append('__asm__(".globl %s\\n\\t.set %s, 0x%08x\\n");   /* %s */'
                   % (sym, sym, val, src))
    text = "\n".join(out) + "\n"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("gen_absyms: %d symbols -> %s" % (len(rows), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
