#!/usr/bin/env python3
"""The N64's reverb for the Xbox's software AICA, as a C table.

The Dreamcast build compiles libultra's AL_FX_CUSTOM reverb
(ssb-decomp-re's dSYAudioCustomFXParams) into an AICA DSP program
(tools/export/ssb_reverbexport.py). That script first builds the reverb as
a NETWORK -- chains of products over the voices' send bus, a delay line
and a few temporaries, rescaled from 32,006 Hz to 44,100 Hz -- and only
then schedules it onto the DSP's 128 steps, in 13-bit coefficients and
the DSP's packed floats.

The Xbox mixer (Platform/xbox/aica/aica_mixer_xbox.c) runs the network
itself, in float: the same chains, the same taps, the same 44.1 kHz pole,
the same sqrt(2) input gain, without the DSP's quantisation. This script
writes it as Platform/xbox/gen/xbox_reverb.h, using ssb_reverbexport's own
functions so the two cannot describe different reverbs.

Always regenerated (it is derived from the decomp).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path[:0] = [os.path.join(ROOT, "tools", d) for d in ("lib", "export")]
import ssb_reverbexport as rx  # noqa: E402

OUT = os.path.join(ROOT, "Platform", "xbox", "gen", "xbox_reverb.h")
KIND = {"mix": 0, "mem": 1, "temp": 2, "state": 3}


def build(decomp):
    params, _ = rx.read_decomp(decomp)
    length, chains, final = rx.network(params)
    writers = {name: tap for tap, name in final.items()}
    users = set()
    for name, terms, _ in chains:
        for _, v in terms:
            if v[0] == "temp":
                users.add(v[1])
    temps = {}
    out_chains, out_terms = [], []
    for name, terms, extra in chains:
        lp = extra.get("lp")
        if lp:
            c = (lp * 16384 >> 15) / 16384.0        # the N64's Q14 pole
            c = c ** (rx.N64_RATE / rx.AICA_RATE)    # same corner at 44.1 kHz
            (_, x), = terms
            nt = [(1.0 - c, x), (c, ("state",))]
        else:
            nt = list(terms)
        first = len(out_terms)
        for coef, v in nt:
            if v[0] == "mix":
                coef *= rx.INPUT_GAIN
                arg = 0
            elif v[0] == "mem":
                arg = rx.scale_tap(v[1])
            elif v[0] == "temp":
                arg = temps[v[1]]
            else:
                arg = 0
            out_terms.append((coef, KIND[v[0]], arg))
        mem_dest = rx.scale_tap(writers[name]) if name in writers else -1
        temp_dest = -1
        if name in users:
            temp_dest = temps[name] = len(temps)
        out_chains.append((name, first, len(nt), mem_dest, temp_dest,
                           1 if lp else 0, 1 if extra.get("ef") else 0))
    return rx.scale_tap(length), out_chains, out_terms, len(temps)


def main():
    decomp = os.environ.get("SSB_DECOMP_DIR", os.path.join(ROOT, "extern", "ssb-decomp-re"))
    length, chains, terms, ntemp = build(decomp)
    taps = [t[2] for t in terms if t[1] == KIND["mem"]] + [c[3] for c in chains if c[3] >= 0]
    lines = [
        "/* GENERATED by tools/xbox/gen_reverb.py from ssb-decomp-re's",
        " * dSYAudioCustomFXParams -- do not edit. The N64's reverb as the network",
        " * tools/export/ssb_reverbexport.py compiles for the AICA DSP, at 44.1 kHz,",
        " * in float (see the generator). */",
        "#ifndef XBOX_REVERB_H",
        "#define XBOX_REVERB_H",
        "",
        "#define XB_RV_RING 32768          /* the DSP's ring (RBL 2); taps reach %d */" % max(taps),
        "#define XB_RV_LENGTH %d            /* the N64 line, rescaled */" % length,
        "#define XB_RV_TEMPS %d" % max(ntemp, 1),
        "#define XB_RV_MIX 0",
        "#define XB_RV_MEM 1",
        "#define XB_RV_TEMP 2",
        "#define XB_RV_STATE 3",
        "",
        "typedef struct { float coef; int kind; int arg; } XbRvTerm;",
        "typedef struct { int first, count, mem_dest, temp_dest, state_dest, ef; } XbRvChain;",
        "",
        "static const XbRvTerm kXbRvTerms[] = {",
    ]
    for coef, kind, arg in terms:
        lines.append("    { %.9ff, %d, %d }," % (coef, kind, arg))
    lines.append("};")
    lines.append("")
    lines.append("static const XbRvChain kXbRvChains[] = {")
    for name, first, count, md, td, sd, ef in chains:
        lines.append("    { %d, %d, %d, %d, %d, %d },   /* %s */" % (first, count, md, td, sd, ef, name))
    lines.append("};")
    lines.append("")
    lines.append("#define XB_RV_CHAINS %d" % len(chains))
    lines.append("")
    lines.append("#endif /* XBOX_REVERB_H */")
    text = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("gen_reverb: %d chains, %d terms, %d temps, line %d -> %s"
          % (len(chains), len(terms), ntemp, length, os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
