/* Give every loaded pack back; rows that share one (wpModelLoad) free it
 * once. Safe to call twice. */
void wpManagerReleaseModels(void)
{
    u32 i, j;

    for (i = 0; i < ARRAY_COUNT(sWPManagerModels); i++)
    {
        Fighter *pack = sWPManagerModels[i].loaded;

        if (!sWPManagerModels[i].is_loaded)
        {
            continue;
        }
        for (j = i; j < ARRAY_COUNT(sWPManagerModels); j++)
        {
            if (sWPManagerModels[j].is_loaded &&
                sWPManagerModels[j].loaded == pack)
            {
                sWPManagerModels[j].loaded = NULL;
                sWPManagerModels[j].is_loaded = FALSE;
            }
        }
        if (pack != NULL)
        {
            fighter_release(pack);
            free(pack);
        }
    }
}

