static sb32 wpManagerAddModel(GObj *weapon_gobj, WPDesc *wp_desc, WPAttributes *attr)
{
#ifdef FT_HOSTTEST
    /* The host cross-test links the scene but not the renderer, so there
     * is no pack to build a tree from; a bare DObj gives MakeWeapon the
     * translate it writes below and lets every field-fill be checked. As
     * efManagerAddModel's host arm. */
    (void)wp_desc;
    (void)attr;

    if (gcAddDObjRpyR(weapon_gobj, NULL) == NULL)
    {
        return FALSE;
    }
    /* A per-fighter MakeWeapon wrapper (wpMarioFireballMakeWeapon and its
     * kin) writes the model's animation frame into DObjGetStruct(g)->mobj->
     * palette_id after the weapon is made. The bare DObj above carries no
     * MObj, so give the host stub a real one from the pool -- not a static:
     * gcEjectDObj hands every dobj->mobj back with gcSetMObjPrevAlloc, and a
     * static would corrupt the allocator on the weapon's eject. gcAddMObj-
     * ForDObj takes a pool MObj and links it, so the eject frees it clean. */
    {
        static MObjSub stub_sub;    /* zeroed; gcAddMObjForDObj copies it */
        gcAddMObjForDObj(DObjGetStruct(weapon_gobj), &stub_sub);
    }
    return TRUE;
#else
    WPModel *m;
    Fighter *pack;
    DObj *root;

    /* THE DATA-LESS ARM, first, and it is the decomp's own: a weapon whose
     * attributes name no `data` has no display list and no model to look a
     * pack up for. Take it before wpModelPackFor, which would refuse. */
    if (wpManagerIsModelLess(attr) != FALSE)
    {
        if (gcAddDObjRpyR(weapon_gobj, NULL) == NULL)
        {
            return FALSE;
        }
        wpManagerSetTransformTypes(DObjGetStruct(weapon_gobj),
                                   &wp_desc->transform_types);
        return TRUE;
    }

    m = wpModelPackFor(wp_desc);

    if (m == NULL)
    {
        syDebugPrintf("wpmanager: no pack for the WPDesc at 0x%08X\n",
                      (unsigned)(uintptr_t)wp_desc);
        return FALSE;
    }
    pack = wpModelLoad(m);

    if (pack == NULL)
    {
        syDebugPrintf("wpmanager: %s did not load\n", m->pack);
        return FALSE;
    }
    if (dc_model_add_dobjs(weapon_gobj, NULL, pack, NULL) < 0)
    {
        syDebugPrintf("wpmanager: no DObj tree for %s\n", m->pack);
        return FALSE;
    }
    root = DObjGetStruct(weapon_gobj);

    if (root != NULL)
    {
        DObj *dobj;

        wpManagerSetTransformTypes(root, &wp_desc->transform_types);

        for (dobj = gcGetTreeDObjNext(root); dobj != NULL;
             dobj = gcGetTreeDObjNext(dobj))
        {
            wpManagerSetTransformTypes(dobj, &wp_desc->transform_types);
        }
    }
    /* wp/wpmanager.c:273-281's gcAddMObjAll / gcAddAnimAll, as the pack's
     * own sections -- dc_model_add_mobjs is gcAddMObjAll followed by
     * gcAddMatAnimJointAll. A pack with no MObjs does nothing, which is
     * fine. */
    dc_model_add_mobjs(weapon_gobj, pack, 0.0F);

    /* The AnimJoint half, attr->anim_joints, as the pack's animation 0.
     * Without it no weapon tree moves on its own: Link's
     * boomerang did not spin (its joint 1 turns ROTX 0 to 2pi every six
     * frames, LinkSpecial3 0x6CC), and neither did Kirby's cutter,
     * Link's Spin Attack, the ground Thunder Jolt or PK Thunder's head.
     * The decomp's condition, on the record: a weapon whose attributes
     * name no AnimJoint does not get one. */
    if (attr->anim_joints != NULL)
    {
        AObjEvent32 **anim_joints = wpModelAnimJoints(pack);

        if (anim_joints != NULL)
        {
            gcAddAnimJointAll(weapon_gobj, anim_joints, 0.0F);
        }
    }
    /* The ground Thunder Jolt plays that same animation again every time
     * it changes which line it rides (wpPikachuThunderJoltGroundAddAnim,
     * which hands gcAddAnimAll Special3's ThunderJoltB tables -- the very
     * ones its attributes name, so they are the pack's animation 0 and
     * its MatAnimJoint). Point the two symbols at the pack's. */
    if (wp_desc == &dWPPikachuThunderJoltGroundWeaponDesc)
    {
        wpAttrsBindJoltB((void **)wpModelAnimJoints(pack),
                         (void ***)wpModelMatAnimJoints(pack),
                         pack->hd->joint_count);
    }
    return TRUE;
#endif
}

