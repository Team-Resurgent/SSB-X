/* efModelLoad's twin: mallocs the pack's Fighter once and keeps it for the
 * run (the malloc heap is not the scene heap), rather than a static per
 * weapon. See src/dc/efmanager.c for why load-time allocation and not
 * .bss. */
static Fighter *wpModelLoad(WPModel *m)
{
    int pal_bank = 0;

    if (!m->is_loaded)
    {
        Fighter *pack;
        u32 i;

        /* Two rows can name one file -- the Thunder's head and trail share
         * wppikachuthunder.mdl -- and the preload below loads one copy
         * for both rows in one tic. A row whose file
         * another row has is a pointer to that row's, as efModelLoad's. */
        for (i = 0; i < ARRAY_COUNT(sWPManagerModels); i++)
        {
            if (sWPManagerModels[i].is_loaded &&
                strcmp(sWPManagerModels[i].pack, m->pack) == 0)
            {
                m->loaded = sWPManagerModels[i].loaded;
                m->is_loaded = TRUE;
                return m->loaded;
            }
        }
        pack = malloc(sizeof(Fighter));

        if (pack == NULL)
        {
            syDebugPrintf("wpmanager: no room for %s's Fighter\n", m->pack);
            return NULL;
        }
        if (fighter_load(pack, m->pack, &pal_bank) != 0)
        {
            free(pack);
            return NULL;
        }
        m->loaded = pack;
        m->is_loaded = TRUE;
    }
    return m->loaded;
}

