/* wp/wpmanager.c:28-49 wpManagerAllocWeapons 0x801654B0, verbatim.
 * No bzero: the game leaves the pool uninitialised and lets
 * wpManagerMakeWeapon fill every field. */
void wpManagerAllocWeapons(void)
{
    WPStruct *wp;
    s32 i;

    syTaskmanSetDrawPassHook(wpManagerResetDLHeads);

    sWPManagerStructsAllocFree = wp = syTaskmanMalloc(sizeof(WPStruct) * WEAPON_ALLOC_MAX, 0x8);

    for (i = 0; i < (WEAPON_ALLOC_MAX - 1); i++)
    {
        wp[i].next = &wp[i + 1];
    }
    if (wp != NULL)
    {
        wp[i].next = NULL;
    }
    sWPManagerGroupID = 1;
    sWPManagerDisplayMode = nDBDisplayModeMaster;
}

/* wp/wpmanager.c:52-64 wpManagerGetNextStructAlloc 0x80165558, verbatim */
WPStruct* wpManagerGetNextStructAlloc(void)
{
    WPStruct *new_weapon = sWPManagerStructsAllocFree;
    WPStruct *get_weapon;

    if (new_weapon == NULL)
    {
        return NULL;
    }
    get_weapon = new_weapon;

    sWPManagerStructsAllocFree = new_weapon->next;

    return get_weapon;
}

/* wp/wpmanager.c:67-72 wpManagerSetPrevStructAlloc 0x80165588, verbatim */
void wpManagerSetPrevStructAlloc(WPStruct *wp)
{
    wp->next = sWPManagerStructsAllocFree;

    sWPManagerStructsAllocFree = wp;
}

/* wp/wpmanager.c:75-83 wpManagerGetGroupID 0x801655A0, verbatim.
 * The decomp warns: do NOT declare with a void argument -- PK Thunder
 * passes unused arguments to it. Kept as an empty-parens (unprototyped)
 * declaration to match, so a caller with extra args still links. */
u32 wpManagerGetGroupID()
{
    u32 group_id = sWPManagerGroupID++;

    if (sWPManagerGroupID == 0)
    {
        sWPManagerGroupID++;
    }
    return group_id;
}

