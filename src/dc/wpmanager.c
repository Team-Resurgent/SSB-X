/* sys/taskman.c:147 gSYTaskmanDLHeads, DIVERGES: the four
 * RSP display-list heads. The port has no display lists -- a port source
 * that would write one goes through src/dc/lbpdraw.h, whose LBPDRAW_MODEL
 * macros turn the gDP/gSP calls into PVR state or into nothing -- so the
 * heads exist for the display procs that still write the game's commands
 * and have nothing to read them:
 *   - wp/wpyoshi/wpyoshieggthrow.c's wpYoshiEggThrowProcDisplay, compiled
 *     unmodified: a pipe sync and an env colour on head 1 before
 *     wpDisplayDLHead1;
 *   - src/dc/itkabigon.c, itspear.c and itpippi.c, verbatim: pipe syncs
 *     and render modes on head 0 around Snorlax's, Clefairy's and the
 *     swarm's draws.
 * The definition lives here rather than in src/dc/taskman.c because
 * tools/check/lbparticle_check.py's oracle links taskman.c beside its own
 * driver, which defines these heads itself to count what the decomp's
 * particle code writes.
 *
 * The heads point into a scratch buffer, and wpManagerResetDLHeads puts
 * them back at its start before every draw pass. The N64 did that at the
 * top of each frame (sys/taskman.c:297-310). Without the reset, the
 * Yoshi's egg's 16 bytes a frame walk off a 64-command buffer and on
 * through .bss until they zero the item spawner's pool
 * (gITManagerAppearActor), whose search then never ends. The fifth row
 * is slack, so an overflow lands in the scratch; the check below stops
 * the game on it, as sys/taskman.c:324-327 prints it. Nothing ever reads
 * the buffer.
 *
 * The reset must not depend on a scene allocating a weapon pool: a scene
 * that left sSYTaskmanDrawPassHook NULL would never put the heads back
 * and every display-list command it wrote would advance them for good.
 * That is the Yoshi's-egg walk again, one level up: mvending.c's
 * room fade/light procs and scstaffroll.c's highlight proc write the
 * game's own gDPFillRectangle strokes here every pass, ~50-90 bytes a
 * frame, and with nothing resetting the head they marched out of this
 * buffer and straight through .bss -- through fgm.c's sLock (hence
 * nSCKindEnding's "m->type <= MUTEX_TYPE_RECURSIVE" assert in
 * fgm_advance, ~10 KB along) and on into taskman.c's own
 * sSYTaskmanDefaultFunction (hence nSCKindStaffroll's wild jump through
 * scene_draw, ~26 KB along). Both crashes were this one walk
 * at two different distances. The reset is installed at boot
 * (wpManagerInitDLHeads, called from src/game/ssb64/main.c) so it does
 * not depend on a scene having weapons; wpManagerAllocWeapons keeps its
 * own call, which is simply redundant. */
/* 64 commands, which every scene up to here lived inside,
 * is not enough for a 1P intro card. sc1pintro.c:1081
 * sc1PIntroVSFighterProcDisplay -- compiled unmodified, like the procs
 * above -- writes seven commands on head 0 for every fighter on the
 * card, four before the fighter and three after, and a card holds one
 * fighter per enemy the rung deals. The Fighting Polygons' rung
 * overflowed it at 560 bytes: ten fighters (the ten Polygon kinds
 * sc1PIntroSetupFighterFiles loads) times seven commands times eight
 * bytes, exactly. The Yoshi Team's rung shows twenty-one, which is
 * 1176. 512 commands is that worst card with the shadow, effect and
 * particle procs that share the head beside it, and room over. Nothing
 * reads the buffer -- the size is a bound on the walk the check below
 * catches, not a capacity -- so the cost is 20 K of .bss for the five. */
#define WPMANAGER_DL_SCRATCH_CMDS 512
static Gfx sWPManagerDLScratch[5][WPMANAGER_DL_SCRATCH_CMDS];
Gfx *gSYTaskmanDLHeads[4] = {
    sWPManagerDLScratch[0], sWPManagerDLScratch[1],
    sWPManagerDLScratch[2], sWPManagerDLScratch[3]
};

/* Installed by wpManagerAllocWeapons; syTaskmanCommonTaskDraw calls it
 * before each pass. */
static void wpManagerResetDLHeads(void)
{
    s32 i;

    for (i = 0; i < ARRAY_COUNT(gSYTaskmanDLHeads); i++)
    {
        if (gSYTaskmanDLHeads[i] > &sWPManagerDLScratch[i][WPMANAGER_DL_SCRATCH_CMDS])
        {
            syDebugPrintf("gtl : DLBuffer over flow !  kind = %d  vol = %d byte\n", i,
                          (s32)((uintptr_t)gSYTaskmanDLHeads[i] - (uintptr_t)sWPManagerDLScratch[i]));
            scManagerRunPrintGObjStatus();
#if defined(DB_HEAP_WALK) || defined(DB_STACK_GUARD) || defined(DB_HEAP_GUARD)
            /* src/dc/db.h's memory hunt: a head past the fifth row walked
             * through .bss, one pass ago -- stop here, where the print
             * above names the pass, and not wherever that write lands */
            if (gSYTaskmanDLHeads[i] >
                &sWPManagerDLScratch[4][WPMANAGER_DL_SCRATCH_CMDS])
            {
                abort();
            }
#endif
        }
        gSYTaskmanDLHeads[i] = sWPManagerDLScratch[i];
    }
}

/* Installs that reset for the whole run, not just for a scene that
 * allocates weapons -- see the walk this fixes in the comment above.
 * Called once from src/game/ssb64/main.c's boot, before the scene
 * manager's first scene; the host test's own driver gets it through
 * wpManagerAllocWeapons as before. */
void wpManagerInitDLHeads(void)
{
    syTaskmanSetDrawPassHook(wpManagerResetDLHeads);
    wpManagerResetDLHeads();
}

